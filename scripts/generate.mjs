#!/usr/bin/env node
// Regenerates src/generated/studio-api.ts from the SplatterVault Studio API description (OpenAPI 3.0).
//
//   npm run generate                         # from the committed copy, openapi/studio-api.json
//   npm run generate -- ./some/swagger.json  # from another local file (copied over openapi/studio-api.json)
//   npm run generate -- https://splattervault.com/docs/studio/swagger.json
//                                            # download, save to openapi/studio-api.json, then generate
//
// Both outputs are committed: the copy of the description (the contract test reads it) and the types.
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import openapiTS, { astToString } from "openapi-typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const specPath = resolve(root, "openapi/studio-api.json");
const outPath = resolve(root, "src/generated/studio-api.ts");

const source = process.argv[2] ?? process.env.SV_STUDIO_SPEC;

async function loadSource() {
  if (!source) return readFile(specPath, "utf8");
  if (/^https?:\/\//i.test(source)) {
    const res = await fetch(source, { headers: { accept: "application/json" } });
    if (!res.ok) throw new Error(`GET ${source} answered ${res.status}`);
    return res.text();
  }
  return readFile(resolve(process.cwd(), source), "utf8");
}

const text = await loadSource();
const doc = JSON.parse(text);
if (typeof doc.openapi !== "string" || !doc.paths) throw new Error("not an OpenAPI document");
if (source) await writeFile(specPath, `${JSON.stringify(doc, null, 2)}\n`);

const ast = await openapiTS(doc, {
  // Every schema property the API marks additionalProperties: true stays open; nothing else is invented.
  additionalProperties: false,
  alphabetize: false,
  defaultNonNullable: true,
  exportType: false
});

const banner = [
  "/**",
  " * Generated by scripts/generate.mjs from openapi/studio-api.json",
  ` * (${doc.info?.title ?? "SplatterVault Studio API"} ${doc.info?.version ?? ""}). Do not edit by hand: run \`npm run generate\`.`,
  " */",
  "/* eslint-disable */",
  ""
].join("\n");

await writeFile(outPath, banner + astToString(ast));
const ops = Object.values(doc.paths).flatMap((item) => Object.values(item).filter((op) => op && op.operationId));
console.log(`wrote ${outPath} (${ops.length} operations, ${Object.keys(doc.components?.schemas ?? {}).length} schemas)`);
