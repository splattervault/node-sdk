#!/usr/bin/env node
// Makes dist/index.js (the `import` entry) a thin ES module over dist/index.cjs (the `require` entry), so a process
// that loads the SDK both ways (an ESM app with a CommonJS dependency, say) holds ONE copy: one SplatterVaultError
// class (instanceof works across both), one player-token key cache. Run after tsup.
import { createRequire } from "node:module";
import { existsSync, unlinkSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const dist = resolve(dirname(fileURLToPath(import.meta.url)), "../dist");
const cjs = createRequire(import.meta.url)(join(dist, "index.cjs"));
const names = Object.keys(cjs).filter((n) => n !== "__esModule" && n !== "default").sort();
if (names.length === 0) throw new Error("dist/index.cjs exports nothing");
for (const n of names) if (!/^[A-Za-z_$][\w$]*$/.test(n)) throw new Error(`export name ${n} cannot be re-exported`);

const text = [
  "// The ES module entry of @splattervault/server: the CommonJS build re-exported, so that `import` and `require`",
  "// share one copy of the SDK (one SplatterVaultError class, one key cache). Generated by scripts/esm-wrapper.mjs.",
  'import sdk from "./index.cjs";',
  "",
  `export const {\n  ${names.join(",\n  ")}\n} = sdk;`,
  ""
].join("\n");
writeFileSync(join(dist, "index.js"), text);
if (existsSync(join(dist, "index.js.map"))) unlinkSync(join(dist, "index.js.map"));
console.log(`dist/index.js: ESM wrapper over dist/index.cjs (${names.length} exports)`);
